// Writes src/core/rules/crash/commandErrorTable.ts: the messages Klipper raises as command errors, taken from
// its Python source, so the command-error rule names only what Klipper itself can say.
// Usage: node scripts/gen-command-errors.mjs <klipper checkout>
import { execFileSync } from 'node:child_process';
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const klipper = process.argv[2];
if (!klipper) {
  console.error('Usage: node scripts/gen-command-errors.mjs <klipper checkout>');
  process.exit(2);
}
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const commit = execFileSync('git', ['-C', klipper, 'rev-parse', '--short=7', 'HEAD'], { encoding: 'utf8' }).trim();

const walk = (d) => readdirSync(d).flatMap((f) => {
  const p = join(d, f);
  return statSync(p).isDirectory() ? walk(p) : p.endsWith('.py') ? [p] : [];
});

// A call that raises a command error, then its string literals. These are the ways the source names the error class:
// gcmd.error, self.gcode.error, gcode.error, printer.command_error, self.error inside gcode.py, and subclasses such
// as BedMeshError. config.error, mcu.error and the rest stop Klipper a different way, and other rules read those.
const CALL = /(?:\b(?:gcmd|gcode|self\.gcode|self\.gcmd)\.error|\bcommand_error|\bCommandError|\bself\.error|\b(?:BedMesh|ProbePoints?|Homing)\w*Error)\s*\(\s*((?:(?:"(?:[^"\\\n]|\\.)*"|'(?:[^'\\\n]|\\.)*')\s*)+)/g;
const LITERAL = /"((?:[^"\\\n]|\\.)*)"|'((?:[^'\\\n]|\\.)*)'/g;
const PLACEHOLDER = /%[-.\d]*[a-zA-Z]/g;

const seen = new Map();
for (const path of walk(join(klipper, 'klippy'))) {
  const file = relative(klipper, path).replace(/\\/g, '/');
  // The class named "error" in these files is not a command error.
  const selfError = file === 'klippy/gcode.py';
  for (const m of readFileSync(path, 'utf8').matchAll(CALL)) {
    if (m[0].startsWith('self.error') && !selfError) continue;
    const text = [...m[1].matchAll(LITERAL)].map((x) => x[1] ?? x[2]).join('');
    // Klipper logs the whole message, so its first line is a line of the log.
    const first = text.split('\\n')[0].replace(/\\(["'\\])/g, '$1').trim();
    if (first.startsWith('%')) continue;
    if (first.replace(PLACEHOLDER, '').replace(/[^A-Za-z]/g, '').length < 10) continue;
    if (!seen.has(first)) seen.set(first, file);
  }
}

const rows = [...seen].sort((a, b) => (a[1] + a[0] < b[1] + b[0] ? -1 : 1));
const body = rows.map(([message, file]) => `  [${JSON.stringify(message)}, ${JSON.stringify(file)}],`).join('\n');
const out = `// Generated by scripts/gen-command-errors.mjs from the Klipper source. Do not edit by hand.

export const KLIPPER_COMMIT = '${commit}';

/** [message as written in the source, with %s placeholders; the file that raises it]. */
export const COMMAND_ERRORS: readonly (readonly [string, string])[] = [
${body}
];
`;
writeFileSync(join(root, 'src/core/rules/crash/commandErrorTable.ts'), out);
console.log(`wrote ${rows.length} messages from Klipper ${commit}`);
